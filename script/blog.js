// ======================================================
// RENDER BLOGS
// ======================================================

function renderBlogs() {

    blogGrid.innerHTML = "";


    const startIndex =
        (currentPage - 1) *
        blogsPerPage;


    const endIndex =
        startIndex +
        blogsPerPage;


    const currentBlogs =
        filteredBlogs.slice(
            startIndex,
            endIndex
        );


    if (currentBlogs.length === 0) {

        emptyState.classList.add("show");

        pagination.innerHTML = "";

        return;

    }


    emptyState.classList.remove("show");


    currentBlogs.forEach(blog => {

        blogGrid.appendChild(
            createBlogCard(blog)
        );

    });


    addReadMoreEvents();

    renderPagination();

}


// ======================================================
// READ MORE
// ======================================================

function addReadMoreEvents() {

    const links =
        document.querySelectorAll(
            ".blog-read"
        );


    links.forEach(link => {

        link.addEventListener(
            "click",
            function () {

                const id =
                    Number(
                        this.dataset.id
                    );


                openBlog(id);

            }
        );

    });

}


// ======================================================
// OPEN BLOG
// ======================================================

function openBlog(id) {

    if (id === "featured") {

        alert(
            `Opening: ${featuredBlog.title}`
        );

        return;

    }


    const blog =
        blogs.find(
            item => item.id === id
        );


    if (!blog) return;


    /*
        Later you can replace the alert
        with your actual blog details page.

        Example:

        window.location.href =
        `blog-details.html?id=${blog.id}`;
    */

    alert(
        `Opening: ${blog.title}`
    );

}


// ======================================================
// PAGINATION
// ======================================================

function renderPagination() {

    pagination.innerHTML = "";


    const totalPages =
        Math.ceil(
            filteredBlogs.length /
            blogsPerPage
        );


    // Previous button

    const previous =
        document.createElement("button");


    previous.className =
        "page-btn";


    previous.textContent =
        "<";


    previous.disabled =
        currentPage === 1;


    previous.addEventListener(
        "click",
        function () {

            if (currentPage > 1) {

                currentPage--;

                renderBlogs();

                scrollToArticles();

            }

        }
    );


    pagination.appendChild(previous);


    // Page numbers

    for (
        let page = 1;
        page <= totalPages;
        page++
    ) {

        const button =
            document.createElement("button");


        button.className =
            "page-btn";


        button.textContent =
            page;


        if (page === currentPage) {

            button.classList.add(
                "active"
            );

        }


        button.addEventListener(
            "click",
            function () {

                currentPage =
                    page;

                renderBlogs();

                scrollToArticles();

            }
        );


        pagination.appendChild(button);

    }


    // Next button

    const next =
        document.createElement("button");


    next.className =
        "page-btn";


    next.textContent =
        ">";


    next.disabled =
        currentPage === totalPages;


    next.addEventListener(
        "click",
        function () {

            if (
                currentPage <
                totalPages
            ) {

                currentPage++;

                renderBlogs();

                scrollToArticles();

            }

        }
    );


    pagination.appendChild(next);

}


// ======================================================
// SCROLL TO ARTICLES
// ======================================================

function scrollToArticles() {

    document
        .querySelector(".latest-header")
        .scrollIntoView({
            behavior: "smooth",
            block: "start"
        });

}


// ======================================================
// CATEGORIES
// ======================================================

function createCategories() {

    const categories = {};


    blogs.forEach(blog => {

        if (!categories[blog.category]) {

            categories[blog.category] = 0;

        }


        categories[blog.category]++;

    });


    categoryList.innerHTML = "";


    const allItem =
        document.createElement("div");


    allItem.className =
        "category-item active";


    allItem.innerHTML = `

        <span class="category-name">

            <i class="fa-solid fa-caret-down"></i>
            <span>
                All Categories
            </span>

        </span>

        <span class="category-count">
            ${blogs.length}
        </span>

    `;


    allItem.addEventListener(
        "click",
        function () {

            selectedCategory =
                "All Categories";

            currentPage = 1;

            updateCategoryActive();

            applyFilters();

        }
    );


    categoryList.appendChild(allItem);


    Object.entries(categories)
        .forEach(
            ([category, count]) => {

                const item =
                    document.createElement(
                        "div"
                    );


                item.className =
                    "category-item";


                item.dataset.category =
                    category;


                item.innerHTML = `

                    <span class="category-name">

                        <i class="fa-solid fa-caret-right"></i>

                        <span>
                            ${category}
                        </span>

                    </span>

                    <span class="category-count">
                        ${count}
                    </span>

                `;


                item.addEventListener(
                    "click",
                    function () {

                        selectedCategory =
                            category;

                        currentPage = 1;

                        updateCategoryActive();

                        applyFilters();

                    }
                );


                categoryList.appendChild(
                    item
                );

            }
        );

}


// ======================================================
// CATEGORY ACTIVE STATE
// ======================================================

function updateCategoryActive() {

    const items =
        document.querySelectorAll(
            ".category-item"
        );


    items.forEach(item => {

        const category =
            item.dataset.category ||
            "All Categories";


        item.classList.toggle(
            "active",
            category === selectedCategory
        );

    });

}


