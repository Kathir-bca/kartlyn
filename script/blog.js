// ======================================================
// SEARCH
// ======================================================

function applyFilters() {

    const searchText =
        searchInput.value
            .trim()
            .toLowerCase();


    filteredBlogs =
        blogs.filter(blog => {


            const matchesSearch =
                !searchText ||

                blog.title
                    .toLowerCase()
                    .includes(searchText) ||

                blog.description
                    .toLowerCase()
                    .includes(searchText) ||

                blog.category
                    .toLowerCase()
                    .includes(searchText);


            const matchesCategory =
                selectedCategory ===
                "All Categories" ||

                blog.category ===
                selectedCategory;


            return (
                matchesSearch &&
                matchesCategory
            );

        });


    applySort();

}


// ======================================================
// SORT
// ======================================================

function applySort() {

    const sort =
        sortBlogs.value;


    if (sort === "latest") {

        filteredBlogs.sort(
            (a, b) =>
                b.id - a.id
        );

    }


    else if (sort === "oldest") {

        filteredBlogs.sort(
            (a, b) =>
                a.id - b.id
        );

    }


    else if (sort === "az") {

        filteredBlogs.sort(
            (a, b) =>
                a.title.localeCompare(
                    b.title
                )
        );

    }


    else if (sort === "za") {

        filteredBlogs.sort(
            (a, b) =>
                b.title.localeCompare(
                    a.title
                )
        );

    }


    renderBlogs();

}


// Search input

searchInput.addEventListener(
    "input",
    function () {

        currentPage = 1;

        applyFilters();

    }
);


// Search button

searchButton.addEventListener(
    "click",
    function () {

        currentPage = 1;

        applyFilters();

    }
);


// Sort

sortBlogs.addEventListener(
    "change",
    function () {

        currentPage = 1;

        applyFilters();

    }
);


